/**
 * The script of the walkthrough video: one spoken line per scene, and the steps that show it.
 *
 * - `say`      caption text (also what is spoken, unless `speak` is set)
 * - `speak`    the same sentence spelled for the voice (abbreviations, names)
 * - `prepare`  runs before recording starts (page loads, so no loading states are filmed)
 * - `run`      runs while recording; the scene then holds until the voice ends + `tail`
 * - `thumbnail` marks the scene the thumbnail frame is taken from
 *
 * Story: a bad flight, the report read top-down, the fix, the next flight that verifies it, then
 * the rest of the toolbox. Scenes share one browser, so later ones build on earlier ones: the
 * first upload's report id is kept in `ids`. Every log is uploaded through the page.
 *
 * Locators come from the components and frontend/messages/en.json; where a text changes there,
 * change it here too. `s.still(...)` names match the images in docs/WALKTHROUGH.md.
 */

import path from "node:path";

/** Sample logs from tests/sample_logs (synthetic, generated by scripts/generate_sample_logs.py). */
export const LOGS = {
  flawed: "sample_flawed.ulg",
  clean: "sample_clean.ulg",
};

export const reportHeading = (page, file) => page.getByRole("heading", { level: 1, name: file, exact: true });
const dropZone = (page) => page.getByText("Drop a flight log here, or click to choose one", { exact: true }).locator("..");
const params = (page) => page.locator("#params");
const changesPanel = (page) => page.getByRole("region", { name: "Applied changes" });

/**
 * Wait until the report for `file` is on screen; throws with the app's own message when an error
 * shows instead (upload refused, analysis failed, API unreachable). Returns the report id.
 */
export async function waitForReport(s, page, file, options) {
  const done = reportHeading(page, file);
  // inside <main>: Next's route announcer is a role=alert too
  const problem = page.locator("main").getByRole("alert");
  await s.waitFor(done.or(problem).first(), options);
  if (await problem.first().isVisible()) {
    const text = (await problem.first().innerText()).replace(/\s+/g, " ").trim();
    const hint = /limit reached/i.test(text) ? " Raise RATE_LIMIT_PER_HOUR for this API (README.md) and restart it." : "";
    throw new Error(`FlightMD showed an error instead of the report for ${file}: "${text}".${hint}`);
  }
  return decodeURIComponent(new URL(page.url()).pathname.split("/").pop());
}

/** The home page, ready for an upload. */
export async function openHome(s, page) {
  await s.goto("/", page.getByRole("heading", { level: 1, name: "Find out why your drone flew badly." }));
}

/**
 * Pick `file` in the drop zone. While it is analysed the page shows real progress and, once the
 * parser has a rate, the time left; that screen is filmed if it is still up when the page loads.
 */
export async function uploadAndWait(s, page, file, logsDir, { still } = {}) {
  await s.pickFile(dropZone(page), path.join(logsDir, file), page.getByLabel("Flight log file"));
  const waiting = page.getByRole("heading", { level: 1, name: "Analysing your flight log" });
  const done = reportHeading(page, file);
  await s.waitFor(waiting.or(done).or(page.locator("main").getByRole("alert")).first());
  if (await waiting.isVisible()) {
    if (still) await s.still(still);
    // short timeout: the analysis may finish while the pointer is still on its way
    await s
      .spotlight(page.locator("main").getByText(/ left\. The page updates itself|^Usually about/), "Real progress from the parser, and the time left", { timeout: 1500 })
      .catch(() => {});
  } else {
    s.log(`  note: ${file} was analysed before the page loaded, so the progress screen wasn't filmed`);
  }
  const id = await waitForReport(s, page, file);
  await s.clearSpotlight();
  return id;
}

